"""
Уведомления администраторам — единая точка рассылки по всем ID из
settings.admin_ids.

Day 5: notify_admins() — вынесено сюда, т.к. и services/dispatch.py
(«0 курьеров на смене»), и handlers/courier.py (смена/назначение/этапы
заказа) одинаково рассылают текст всем админам с одинаковой обработкой
сбоя доставки одному конкретному (best-effort — не должно прерывать
рассылку остальным).

Day 5 hotfix (живой фидбэк): если человек, разместивший заказ, сам же
входит в ADMIN_TELEGRAM_IDS (типичная ситуация при тестировании силами
одного человека — админ одновременно тестирует и как клиент), он видел
ДВА почти одинаковых сообщения об одном и том же переходе статуса:
человеческое клиентское и техническое админское с order_id. В реальной
эксплуатации админ и клиенты — разные люди, это не проявляется вообще,
но лучше не дублировать сообщения тому же человеку в принципе, а не
только "в реальной эксплуатации это не страшно". exclude_user_id —
опциональный параметр: если совпадает с одним из admin_ids, тому
конкретному админу сообщение не отправляется (остальным — отправляется
как обычно).

Уведомления КЛИЕНТУ/КУРЬЕРУ остаются точечными в вызывающем коде —
контекст (кому именно, какой текст) слишком разный на каждый случай,
единой точки для них пока не видно. Если это изменится в Day 6 (полная
статусная модель + тайм-ауты) — стоит пересмотреть.
"""

from __future__ import annotations

import logging

from aiogram import Bot
from aiogram.exceptions import TelegramAPIError

from config import Settings

logger = logging.getLogger(__name__)


async def notify_admins(
    bot: Bot, settings: Settings, text: str, *, exclude_user_id: str | int | None = None
) -> None:
    """
    Best-effort — сбой доставки одному админу (например, заблокировал
    бота) не должен прерывать рассылку остальным. В отличие от
    append_order здесь нет конкретного пользователя, которому нужно
    правдиво сообщить об успехе/провале — молча логируем и продолжаем.

    Живой фидбэк: ловили только TelegramBadRequest — но "бот не может
    написать первым" (пользователь никогда не жал /start этому боту) и
    "бот заблокирован пользователем" — это TelegramForbiddenError,
    СОСЕДНИЙ класс исключений в aiogram, а не подкласс TelegramBadRequest,
    так что эти сбои раньше не ловились этим except вообще и падали
    дальше необработанными. Ловим базовый TelegramAPIError — покрывает
    все варианты сбоя доставки конкретному админу разом.
    """
    exclude = str(exclude_user_id) if exclude_user_id is not None else None
    for admin_id in settings.admin_ids:
        if exclude is not None and str(admin_id) == exclude:
            continue
        try:
            await bot.send_message(admin_id, text)
        except TelegramAPIError as exc:
            logger.warning("Не удалось отправить уведомление админу %s: %s", admin_id, exc)
